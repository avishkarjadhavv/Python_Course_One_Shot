a = [2,7,4,3,9,2,4,3,8]

print(a)

a.append(5) # this will add the element 5 at the end of the list
print(a)

a.sort() # this will sort the list in ascending order
print(a)

a.reverse() # this will reverse the order of the list
print(a)

a.insert(2, 6) # this will insert the element 6 at index 2
print(a)

a.pop() # this will remove the last element of the list and return it

a.pop(1) # this will remove the element at index 1 and return it
print(a)

a.remove(2) # this will remove the first occurrence of the element 2 from the list
print(a)
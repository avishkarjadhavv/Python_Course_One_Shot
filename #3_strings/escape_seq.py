a = "hARRY is a good boy He is my friend"
print(a)

d = '''hARRY is a good boy
 He is my friend'''
print(d)

# if we want to print a string in multiple lines then we can use escape sequence \n

b = "hARRY is a good boy\nHe is my friend"
print(b)

c = "hARRY is a \"good\" boy\tHe is my friend"
print(c)
# in the above string we have used escape sequence \" to print double quotes and \t to print a tab space